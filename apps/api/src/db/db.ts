import { drizzle, type NodePgDatabase } from "drizzle-orm/node-postgres";
import { migrate } from "drizzle-orm/node-postgres/migrator";
import pg from "pg";
import { fileURLToPath } from "node:url";
import path from "node:path";
import * as schema from "./schema.ts";

export type Db = NodePgDatabase<typeof schema>;
// A transaction handle has the same query surface as the database.
export type Tx = Parameters<Parameters<Db["transaction"]>[0]>[0];
export type DbOrTx = Db | Tx;

export const DB = Symbol("DB");
export const PG_POOL = Symbol("PG_POOL");

export function createPool(databaseUrl: string): pg.Pool {
  return new pg.Pool({ connectionString: databaseUrl, max: Number(process.env.DB_POOL_MAX ?? 30) });
}

export function createDb(pool: pg.Pool): Db {
  return drizzle(pool, { schema });
}

// SQL migrations live in apps/api/drizzle (generated by drizzle-kit).
export function migrationsFolder(): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  return path.resolve(here, "../../drizzle");
}

export async function runMigrations(db: Db): Promise<void> {
  await migrate(db, { migrationsFolder: migrationsFolder() });
}
